CREATE TABLE
    auditorias (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        empresa_id BIGINT NOT NULL,
        usuario_id BIGINT,
        entidade VARCHAR(50) NOT NULL,
        registro_id BIGINT NOT NULL,
        acao VARCHAR(30) NOT NULL,
        descricao VARCHAR(500),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT fk_auditorias_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
        CONSTRAINT ck_auditorias_acao CHECK (
            acao IN (
                'CRIAR',
                'ATUALIZAR',
                'DESATIVAR',
                'MOVIMENTAR_ESTOQUE'
            )
        )
    );

CREATE INDEX idx_auditorias_empresa_data ON auditorias (empresa_id, created_at DESC, id DESC);

CREATE INDEX idx_auditorias_entidade_registro ON auditorias (empresa_id, entidade, registro_id);