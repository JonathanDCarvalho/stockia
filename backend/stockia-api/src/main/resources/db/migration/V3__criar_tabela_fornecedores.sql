
CREATE TABLE fornecedores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    documento VARCHAR(14),
    email VARCHAR(150),
    telefone VARCHAR(20),
    contato VARCHAR(100),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_fornecedores_empresa
        FOREIGN KEY (empresa_id)
        REFERENCES empresas (id),

    CONSTRAINT uk_fornecedores_id_empresa
        UNIQUE (id, empresa_id),

    CONSTRAINT ck_fornecedores_documento
        CHECK (
            documento IS NULL
            OR documento ~ '^([0-9]{11}|[0-9]{14})$'
        )
);

CREATE UNIQUE INDEX uk_fornecedores_empresa_documento
ON fornecedores (empresa_id, documento)
WHERE documento IS NOT NULL;

CREATE INDEX idx_fornecedores_empresa
ON fornecedores (empresa_id);

