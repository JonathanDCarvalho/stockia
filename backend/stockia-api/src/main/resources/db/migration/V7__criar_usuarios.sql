CREATE TABLE
    usuarios (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        empresa_id BIGINT NOT NULL,
        nome VARCHAR(150) NOT NULL,
        email VARCHAR(255) NOT NULL,
        senha VARCHAR(255) NOT NULL,
        perfil VARCHAR(20) NOT NULL,
        ativo BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMP NOT NULL,
        updated_at TIMESTAMP NOT NULL,
        CONSTRAINT fk_usuarios_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
        CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('ADMIN', 'OPERADOR'))
    );

CREATE UNIQUE INDEX uk_usuarios_email ON usuarios (LOWER(email));

CREATE INDEX idx_usuarios_empresa ON usuarios (empresa_id);

ALTER TABLE auditorias ADD CONSTRAINT fk_auditorias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id);