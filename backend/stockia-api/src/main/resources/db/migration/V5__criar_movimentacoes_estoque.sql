ALTER TABLE produtos ADD CONSTRAINT uk_produtos_id_empresa UNIQUE (id, empresa_id);

CREATE TABLE
    movimentacoes_estoque (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        empresa_id BIGINT NOT NULL,
        produto_id BIGINT NOT NULL,
        tipo VARCHAR(10) NOT NULL,
        quantidade INTEGER NOT NULL,
        estoque_anterior INTEGER NOT NULL,
        estoque_posterior INTEGER NOT NULL,
        observacao VARCHAR(500),
        created_at TIMESTAMP NOT NULL,
        CONSTRAINT fk_movimentacoes_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
        CONSTRAINT fk_movimentacoes_produto_empresa FOREIGN KEY (produto_id, empresa_id) REFERENCES produtos (id, empresa_id),
        CONSTRAINT ck_movimentacoes_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA', 'AJUSTE')),
        CONSTRAINT ck_movimentacoes_quantidade CHECK (
            (
                tipo = 'AJUSTE'
                AND quantidade >= 0
            )
            OR (
                tipo IN ('ENTRADA', 'SAIDA')
                AND quantidade > 0
            )
        ),
        CONSTRAINT ck_movimentacoes_estoque_anterior CHECK (estoque_anterior >= 0),
        CONSTRAINT ck_movimentacoes_estoque_posterior CHECK (estoque_posterior >= 0)
    );

CREATE INDEX idx_movimentacoes_empresa ON movimentacoes_estoque (empresa_id);

CREATE INDEX idx_movimentacoes_empresa_produto_data ON movimentacoes_estoque (empresa_id, produto_id, created_at DESC);